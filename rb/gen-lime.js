// EXP-REBRAND: generates rb/rb-lime.css from the built page: every rule that hard-codes the old lime accent gets an
// html.rb-on override with only those declarations, recoloured to the v9.1 set (solid lime fills → the red primary with white text,
// lime text → off-white, lime lines/glows → red). Colours only: no other property is emitted. Run after node build.js; re-run when src changes.
const fs = require('fs'); const s = fs.readFileSync('index.html', 'utf8');
const css = [...s.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(m => m[1]).join('\n').replace(/\/\*[\s\S]*?\*\//g, '');
const LIME = /#c6f36b|#d4ff6b|#b8e05a/gi, LIMEA = /rgba\(\s*198\s*,\s*243\s*,\s*107\s*,/gi;
const out = []; const re = /([^{}@]+)\{([^{}]*)\}/g; let m;
while ((m = re.exec(css))) {
  const sel = m[1].trim(), body = m[2]; if (!LIME.test(body) && !LIMEA.test(body)) { LIME.lastIndex = LIMEA.lastIndex = 0; continue; } LIME.lastIndex = LIMEA.lastIndex = 0;
  if (/^(\d|from|to)\b|%$/.test(sel) || /:root|^html\b|#rbApp|rb-on/.test(sel)) continue;
  const decls = body.split(';').map(d => d.trim()).filter(d => d && (LIME.test(d) | LIMEA.test(d)) && (LIME.lastIndex = LIMEA.lastIndex = 0, true));
  if (!decls.length) continue;
  const fill = decls.some(d => /^background(-color)?\s*:\s*(#c6f36b|#d4ff6b|#b8e05a)\b/i.test(d));
  const mapped = decls.map(d => { const [p0, ...v] = d.split(':'); const prop = p0.trim().toLowerCase(); let val = v.join(':');
    if (prop === 'color' || prop === 'fill' || prop === '-webkit-text-fill-color' || prop === 'caret-color') val = val.replace(LIME, '#f3f4f2').replace(LIMEA, 'rgba(243,244,242,');
    else val = val.replace(LIME, '#d7232d').replace(LIMEA, 'rgba(215,35,45,');
    return prop + ':' + val.trim(); });
  if (fill && !decls.some(d => /^color\s*:/i.test(d))) mapped.push('color:#fff!important');
  const pre = sel.split(',').map(x => x.trim()).filter(Boolean).map(x => /^body\b/.test(x) ? 'html.rb-on ' + x : 'html.rb-on ' + x).join(',');
  out.push(pre + '{' + mapped.map(d => /!important/.test(d) ? d : d + '!important').join(';') + '}');
}
fs.writeFileSync('rb/rb-lime.css', '/* generated by rb/gen-lime.js · old lime accents → v9.1 colours (html.rb-on only) */\n' + out.join('\n') + '\n');
console.log('rb-lime.css rules', out.length);
